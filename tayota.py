# 1. Створення словника з описом авто (на прикладі Toyota RAV4 Hybrid)
car = {
    "модель": "Toyota RAV4 Hybrid",
    "ціна": 1600000,
    "обєм_двигуна": 2487,
    "повна_маса": 2225,
    "макс_швидкість": 180,
    "витрата_пального": 4.8,  # на 100 км
    "особливості_інтерєру": [
        "Шкіряне оздоблення керма",
        "Клімат-контроль",
        "Мультимедійна система 8 дюймів"
    ],
    "параметри_багажника": {
        "звичайний": 580,
        "зі_складеними_сидіннями": 1690
    }
}

# 2. Додаємо інформацію про масу причепа
car["макс_маса_причепа"] = 1650

# 3. Отримуємо та виводимо інформацію
print(f"Назва авто: {car['модель']}")
print(f"Ціна: {car['ціна']} грн")
print(f"Перша опція інтер'єру: {car['особливості_інтерєру'][0]}")
print(f"Об'єм багажника (складені сидіння): {car['параметри_багажника']['зі_складеними_сидіннями']} л")

# Рахуємо страховий платіж (0.5% від вартості) та оновлюємо словник
car["страховий_платіж"] = car["ціна"] * 0.005
print(f"Страховий платіж: {car['страховий_платіж']} грн")

# Рахуємо вартість мандрівки на 200 км (бензин по 93 грн/літр)
# Формула: (витрата на 100 км * 2) * ціна бензину
trip_cost = (car["витрата_пального"] * 2) * 93
print(f"Вартість мандрівки на 200 км: {trip_cost} грн")